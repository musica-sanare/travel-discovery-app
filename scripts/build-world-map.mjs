// Builds public/world-map.svg from Natural Earth 1:110m land (public domain,
// https://www.naturalearthdata.com/) with the Equal Earth projection in
// shared/map-projection.ts (docs/working/DECISIONS.md ADR-036). The raw
// GeoJSON is downloaded by hand and never committed.
//
//   node scripts/build-world-map.mjs <ne_110m_land.geojson>
//
// With `--check <ne_50m_admin_0_countries.geojson> <content.json>` it also
// reports, for every destination with a location, whether the point lies on
// the map's land and inside its country (the 1:50m data keeps small islands).
import { readFileSync, writeFileSync } from "node:fs";
import { MAP_HEIGHT, MAP_SOUTH_LIMIT, MAP_WIDTH, toMapPoint } from "../shared/map-projection.ts";

const OUTPUT = new URL("../public/world-map.svg", import.meta.url);

// Content country slugs whose Natural Earth NAME_EN differs.
const COUNTRY_NAMES = { czechia: "Czech Republic", turkiye: "Turkey", "united-states": "United States of America" };

// A coastal city centre can fall just outside the generalized 1:50m outline.
const COAST_TOLERANCE_KM = 5;

function polygonsOf(feature) {
  const { type, coordinates } = feature.geometry;
  return type === "Polygon" ? [coordinates] : type === "MultiPolygon" ? coordinates : [];
}

// One decimal in a 1000-unit-wide frame is about 40 m at the equator, far
// below the detail of 1:110m data.
const round = (value) => Math.round(value * 10) / 10;
const format = (value) => String(round(value)).replace(/^(-?)0\./, "$1.");

function ringPath(ring) {
  const points = [];
  for (const [longitude, latitude] of ring) {
    const { x, y } = toMapPoint(latitude, longitude);
    const point = [round(x), round(y)];
    const last = points.at(-1);
    if (!last || last[0] !== point[0] || last[1] !== point[1]) points.push(point);
  }
  if (points.length < 4) return "";
  let path = `M${format(points[0][0])} ${format(points[0][1])}`;
  for (let i = 1; i < points.length; i++) {
    const dx = format(points[i][0] - points[i - 1][0]);
    const dy = format(points[i][1] - points[i - 1][1]);
    path += `l${dx}${dy.startsWith("-") ? "" : " "}${dy}`;
  }
  return `${path}z`;
}

function buildMap(landPath) {
  const land = JSON.parse(readFileSync(landPath, "utf8"));
  const paths = land.features
    .flatMap(polygonsOf)
    .filter((polygon) => polygon[0].some(([, latitude]) => latitude > MAP_SOUTH_LIMIT))
    .flatMap((polygon) => polygon.map(ringPath))
    .filter(Boolean);
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${String(MAP_WIDTH)} ${String(MAP_HEIGHT)}">` +
    "<!-- Natural Earth 1:110m land (public domain), Equal Earth projection; generated by scripts/build-world-map.mjs -->" +
    `<path fill-rule="evenodd" d="${paths.join("")}"/></svg>\n`;
  writeFileSync(OUTPUT, svg);
  console.log(`Wrote public/world-map.svg: ${String(paths.length)} rings, ${String(Buffer.byteLength(svg))} bytes`);
  return land;
}

// Even-odd ray casting in longitude/latitude, adequate away from the poles and the antimeridian.
function inRing(ring, longitude, latitude) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > latitude !== yj > latitude && longitude < ((xj - xi) * (latitude - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

const inPolygons = (polygons, longitude, latitude) =>
  polygons.some((rings) => rings.filter((ring) => inRing(ring, longitude, latitude)).length % 2 === 1);

function distanceKm(a, b) {
  const rad = Math.PI / 180;
  const h =
    Math.sin(((b[1] - a[1]) * rad) / 2) ** 2 +
    Math.cos(a[1] * rad) * Math.cos(b[1] * rad) * Math.sin(((b[0] - a[0]) * rad) / 2) ** 2;
  return 2 * 6371 * Math.asin(Math.sqrt(h));
}

/** Distance to the nearest vertex: an upper bound on the distance to the shape. */
const nearestKm = (polygons, point) =>
  Math.min(...polygons.flat(2).map((vertex) => distanceKm(point, vertex)));

function check(land, countriesPath, contentPath) {
  const landPolygons = land.features.flatMap(polygonsOf);
  const countries = JSON.parse(readFileSync(countriesPath, "utf8")).features;
  const content = JSON.parse(readFileSync(contentPath, "utf8"));
  let failures = 0;
  for (const destination of content.destinations) {
    const { location } = destination;
    if (!location) continue;
    const point = [location.longitude, location.latitude];
    const expected = COUNTRY_NAMES[destination.country] ?? destination.country;
    const country = countries.find(
      (feature) => feature.properties.NAME_EN.toLowerCase().replaceAll(" ", "-") === expected.toLowerCase().replaceAll(" ", "-"),
    );
    if (!country) {
      failures++;
      console.log(`${destination.slug}: country ${destination.country} not found in the country data`);
      continue;
    }
    const inCountry = inPolygons(polygonsOf(country), ...point);
    const offshoreKm = inCountry ? 0 : nearestKm(polygonsOf(country), point);
    const onLand = inPolygons(landPolygons, ...point);
    if (offshoreKm > COAST_TOLERANCE_KM) failures++;
    console.log(
      [
        destination.slug.padEnd(18),
        `${String(location.latitude).padStart(7)} ${String(location.longitude).padStart(8)}`,
        inCountry
          ? "in country"
          : `${offshoreKm > COAST_TOLERANCE_KM ? "NOT in country" : "at the country's coast"} (nearest vertex ${offshoreKm.toFixed(1)} km)`,
        onLand ? "on map land" : `off map land (nearest vertex ${nearestKm(landPolygons, point).toFixed(1)} km)`,
      ].join("  "),
    );
  }
  if (failures > 0) process.exitCode = 1;
}

const [landPath, flag, countriesPath, contentPath] = process.argv.slice(2);
if (!landPath || (flag !== undefined && (flag !== "--check" || !countriesPath || !contentPath))) {
  console.error("Usage: node scripts/build-world-map.mjs <land.geojson> [--check <countries.geojson> <content.json>]");
  process.exit(2);
}
const land = buildMap(landPath);
if (flag) check(land, countriesPath, contentPath);
